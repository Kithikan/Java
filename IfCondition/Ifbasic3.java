class Ifbasic3{
	public static void main(String args[]){
		
		int marks =26;
		
		if (marks >= 75 && marks<=100){			
			System.out.println("A");
		}	
			
		else if (marks >= 65){
			System.out.println("B");
		}	
				
		else if (marks >= 55){
			System.out.println("C");
		}	
			
		else if (marks >= 35){
			System.out.println("S");
		}
		
		else { 
			System.out.println("fail");
		}	
	}
}